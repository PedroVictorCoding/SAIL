//! Typed contracts for SAIL Studio workspaces, audio projects, and the Music Strategist.
use serde::{Deserialize, Serialize};

pub const STUDIO_PROTOCOL_VERSION: u16 = 1;

/// Request payload for the `studio:audio_analyze` tool.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct AudioAnalyzeRequest {
    /// Absolute or workspace-relative path to the audio file to analyze.
    pub file_path: String,
    /// Optional reference track path to compare against.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reference_file_path: Option<String>,
    /// Target genre hint (e.g., "electronic", "hip-hop", "pop", "rock", "acoustic").
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub genre_hint: Option<String>,
    /// Custom target integrated LUFS (defaults to -14.0 for streaming if omitted).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub target_lufs: Option<f64>,
}

/// Frequency spectrum energy distribution across standard mixing bands.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct FrequencyBands {
    /// Sub-bass: 20 Hz - 60 Hz (kick fundamentals, 808 subs)
    pub sub_bass_db: f64,
    /// Bass: 60 Hz - 250 Hz (bassline warmth, kick punch)
    pub bass_db: f64,
    /// Low-mids: 250 Hz - 500 Hz (mud/body zone, snare body)
    pub low_mids_db: f64,
    /// Midrange: 500 Hz - 2000 Hz (vocal clarity, lead instruments)
    pub midrange_db: f64,
    /// High-mids: 2000 Hz - 6000 Hz (presence, harshness, vocal bite)
    pub high_mids_db: f64,
    /// Brilliance: 6000 Hz - 20000 Hz (air, hi-hat shimmer, breath)
    pub brilliance_db: f64,
}

/// Structural section in a song arrangement with energy measurements.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct AudioSection {
    pub label: String,
    pub start_seconds: f64,
    pub end_seconds: f64,
    pub rms_db: f64,
    pub lufs_short_term: f64,
    pub relative_energy: f64,
}

/// Objective, empirical analysis receipt produced by Bridge audio tools.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct AudioReceipt {
    pub version: u16,
    pub file_path: String,
    pub file_name: String,
    pub duration_seconds: f64,
    pub sample_rate: u32,
    pub channels: u16,
    pub bits_per_sample: u16,
    pub integrated_lufs: f64,
    pub loudness_range_lra: f64,
    pub true_peak_db: f64,
    pub rms_db: f64,
    pub clipping_detected: bool,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub estimated_bpm: Option<f64>,
    pub frequency_bands: FrequencyBands,
    pub sections: Vec<AudioSection>,
    pub analyzed_at_ms: u64,
}

/// High-level strategic review generated by Mind based on the `AudioReceipt`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct StrategistReview {
    pub version: u16,
    pub song_title: String,
    pub genre: String,
    pub target_lufs: f64,
    pub measured_lufs: f64,
    pub lufs_difference: f64,
    pub loudness_verdict: String,
    pub true_peak_db: f64,
    pub headroom_verdict: String,
    pub dynamic_contrast_verdict: String,
    pub tonal_balance_findings: Vec<String>,
    pub strategic_recommendations: Vec<String>,
    pub canvas_card_mermaid: String,
}
