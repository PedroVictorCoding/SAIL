//! Publish a verified Forge patch as a draft pull request.
//!
//! The patch is applied in a throwaway detached `git worktree` based on `origin/main`,
//! committed, and pushed straight to `refs/heads/agent/forge-issue-N`. The user's checkout,
//! its local branches and `main` are never modified, and nothing is ever merged.

use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Duration;

use crate::github::{DraftPr, GithubClient, run_with_timeout};
use crate::persistence::TaskCheckpoint;

const GIT_TIMEOUT: Duration = Duration::from_secs(120);

/// Where and how to publish.
#[derive(Debug, Clone)]
pub struct PublishConfig {
    /// A git checkout of the repository with an `origin` remote.
    pub repo_root: PathBuf,
    /// `owner/name` slug for the GitHub API.
    pub repo_slug: String,
    /// Scratch directory for temporary publish worktrees.
    pub scratch_dir: PathBuf,
    pub base_branch: String,
    pub labels: Vec<String>,
}

fn git(dir: &Path, args: &[&str]) -> Result<String, String> {
    run_with_timeout(
        Command::new("git").arg("-C").arg(dir).args(args),
        GIT_TIMEOUT,
    )
}

/// Build the PR body from the job's checkpoint and report.
pub fn render_pr_body(cp: &TaskCheckpoint) -> String {
    let mut body = String::new();
    body.push_str(&format!(
        "Autonomous patch from SAIL Forge for #{}. **Draft: review before merging.**\n\n",
        cp.issue_number
    ));
    body.push_str("## Verification\n");
    for t in &cp.test_history {
        body.push_str(&format!(
            "- `{}`: {} ({}ms)\n",
            t.command, t.status, t.duration_ms
        ));
    }
    body.push_str("- Deterministic pre-review gates: passed\n");
    if let Some(r) = &cp.review_result {
        body.push_str(&format!(
            "- Review (`{}`): {} (confidence {:.2})\n",
            r.provider,
            if r.verdict.passed {
                "passed"
            } else {
                "not passed"
            },
            r.verdict.confidence_score
        ));
        for e in &r.verdict.untested_edge_cases {
            body.push_str(&format!("  - untested: {e}\n"));
        }
    }
    if let Some(files) = &cp.modified_files {
        body.push_str(&format!("\n## Files\n{}\n", files.join(", ")));
    }
    if let Some(report) = &cp.final_report {
        body.push_str(&format!("\nModel: `{}`\n", report.model_id));
    }
    body.push_str(&format!(
        "Forge job: `{}`\n\nCloses #{}\n",
        cp.job_id, cp.issue_number
    ));
    body
}

/// Push the checkpoint's patch to its Forge branch and open a draft PR. Returns the PR URL.
pub fn publish_draft_pr(
    cfg: &PublishConfig,
    cp: &TaskCheckpoint,
    gh: &dyn GithubClient,
) -> Result<String, String> {
    let patch = cp
        .patch
        .as_deref()
        .filter(|p| !p.trim().is_empty())
        .ok_or("checkpoint has no patch to publish")?;
    let branch = format!("agent/forge-issue-{}", cp.issue_number);

    git(
        &cfg.repo_root,
        &["fetch", "--quiet", "origin", &cfg.base_branch],
    )?;
    let remote_ref = git(
        &cfg.repo_root,
        &[
            "ls-remote",
            "--heads",
            "origin",
            &format!("refs/heads/{branch}"),
        ],
    )?;
    if !remote_ref.trim().is_empty() {
        return Err(format!(
            "remote branch {branch} already exists; refusing to overwrite"
        ));
    }

    std::fs::create_dir_all(&cfg.scratch_dir).map_err(|e| e.to_string())?;
    let dir = cfg.scratch_dir.join(&cp.job_id);
    let dir_str = dir.to_string_lossy().to_string();
    if dir.exists() {
        let _ = git(&cfg.repo_root, &["worktree", "remove", "--force", &dir_str]);
        let _ = std::fs::remove_dir_all(&dir);
    }
    git(
        &cfg.repo_root,
        &[
            "worktree",
            "add",
            "--detach",
            &dir_str,
            &format!("origin/{}", cfg.base_branch),
        ],
    )?;

    let result = (|| {
        let patch_file = cfg.scratch_dir.join(format!("{}.patch", cp.job_id));
        std::fs::write(&patch_file, patch).map_err(|e| e.to_string())?;
        git(&dir, &["apply", "--index", &patch_file.to_string_lossy()]).map_err(|e| {
            format!(
                "stale base: patch no longer applies to origin/{}: {e}",
                cfg.base_branch
            )
        })?;
        let _ = std::fs::remove_file(&patch_file);

        let title = format!(
            "forge: {} (#{})",
            cp.issue_title.as_deref().unwrap_or("autonomous fix"),
            cp.issue_number
        );
        let message = format!(
            "{title}\n\nAutonomous patch generated by SAIL Forge.\n\nForge-Job: {}\nRefs #{}",
            cp.job_id, cp.issue_number
        );
        git(&dir, &["commit", "--quiet", "-m", &message])?;
        git(
            &dir,
            &[
                "push",
                "--quiet",
                "origin",
                &format!("HEAD:refs/heads/{branch}"),
            ],
        )?;

        gh.create_draft_pr(
            &cfg.repo_slug,
            &DraftPr {
                head_branch: branch.clone(),
                base_branch: cfg.base_branch.clone(),
                title,
                body: render_pr_body(cp),
                labels: cfg.labels.clone(),
            },
        )
    })();

    let _ = git(&cfg.repo_root, &["worktree", "remove", "--force", &dir_str]);
    result
}
