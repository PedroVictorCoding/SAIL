use sail_common::error::Result;
use sail_mind::VoiceModelServices;
use serde::{Deserialize, Serialize};
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TtsConfig {
    pub voice_timbre: String,
    pub language: String,
    pub speech_speed: f32,
}
impl Default for TtsConfig {
    fn default() -> Self {
        Self {
            voice_timbre: std::env::var("SAIL_TTS_VOICE").unwrap_or("af_heart".into()),
            language: std::env::var("SAIL_TTS_LANGUAGE").unwrap_or("en-us".into()),
            speech_speed: 1.0,
        }
    }
}
#[derive(Clone)]
pub struct LocalNeuralTts {
    config: TtsConfig,
    services: VoiceModelServices,
    pub threads: usize,
}
impl LocalNeuralTts {
    pub fn new(config: TtsConfig) -> Self {
        Self::with_services(config, VoiceModelServices::new())
    }
    pub fn with_services(config: TtsConfig, services: VoiceModelServices) -> Self {
        Self {
            config,
            services,
            threads: 4,
        }
    }
    pub async fn warm_up(&self) -> Result<()> {
        self.services.warm_tts(self.threads).await
    }
    pub fn set_voice(&mut self, voice: &str, language: &str) {
        self.config.voice_timbre = voice.into();
        self.config.language = language.into();
    }
    pub async fn synthesize_pcm(&self, text: &str) -> Result<(Vec<i16>, u32)> {
        if text.trim().is_empty() {
            return Ok((Vec::new(), 24000));
        }
        let (mut pcm, rate) = self
            .services
            .synthesize(
                text,
                &self.config.voice_timbre,
                &self.config.language,
                self.config.speech_speed,
                self.threads,
            )
            .await?;
        trim_pcm_silence(&mut pcm, rate);
        Ok((pcm, rate))
    }
    pub async fn synthesize(&self, text: &str) -> Result<Vec<u8>> {
        let (pcm, rate) = self.synthesize_pcm(text).await?;
        Ok(crate::stt_wav_encode(&pcm, rate))
    }
}

/// Trims excessive leading and trailing near-silent samples generated by neural TTS,
/// retaining natural phoneme decay (35ms at the end) and onset lead-in (15ms at the start)
/// while avoiding artificial pauses or digital silence between sentences.
pub fn trim_pcm_silence(pcm: &mut Vec<i16>, rate: u32) {
    if pcm.is_empty() {
        return;
    }
    let threshold = 160i16; // ~0.005 of i16::MAX, filters background noise floor
    let retain_tail = (35 * rate as usize) / 1000;
    let retain_lead = (15 * rate as usize) / 1000;

    if let Some(last) = pcm.iter().rposition(|&s| s.abs() > threshold) {
        let keep_end = (last + 1 + retain_tail).min(pcm.len());
        pcm.truncate(keep_end);
    }
    if let Some(first) = pcm.iter().position(|&s| s.abs() > threshold) {
        let skip_start = first.saturating_sub(retain_lead);
        if skip_start > 0 {
            pcm.drain(..skip_start);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn trim_pcm_silence_removes_dead_air_while_preserving_cadence() {
        let rate = 24000;
        let mut pcm = vec![0i16; 2400]; // 100ms leading silence
        pcm.extend(vec![5000i16; 2400]); // 100ms tone
        pcm.extend(vec![0i16; 4800]); // 200ms trailing silence

        trim_pcm_silence(&mut pcm, rate);

        let expected_lead = 15 * rate as usize / 1000; // 360 samples
        let expected_tail = 35 * rate as usize / 1000; // 840 samples
        let tone_len = 2400;
        assert_eq!(pcm.len(), expected_lead + tone_len + expected_tail);
        assert_eq!(&pcm[..expected_lead], &vec![0i16; expected_lead][..]);
        assert_eq!(&pcm[expected_lead..expected_lead + 5], &[5000, 5000, 5000, 5000, 5000]);
    }

    #[test]
    fn trim_pcm_silence_handles_empty_or_silent_buffer() {
        let mut empty = Vec::<i16>::new();
        trim_pcm_silence(&mut empty, 24000);
        assert!(empty.is_empty());

        let mut silent = vec![0i16; 1000];
        trim_pcm_silence(&mut silent, 24000);
        assert_eq!(silent.len(), 1000);
    }
}
